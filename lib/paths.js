/**
 * Path, naming, and local-date math for the memory tree.
 *
 * All of this module is pure (no I/O, no DSH dependency) so it can be unit
 * tested with plain `node`. The naming rules are normative — see
 * `<root>\index.md`:
 *
 *   <root>/index.md                              human/agent maintained, plugin never rewrites
 *   <root>/longterm.md                           one line per year (highest level)
 *   <root>/<yyyy>/<yyyy>.md                      year roll-up (one line per month)
 *   <root>/<yyyy>/<mm>/<yyyy>-<mm>.md            month roll-up (one line per day)
 *   <root>/<yyyy>/<mm>/<dd>/<yyyy>-<mm>-<dd>.md  day roll-up + snapshot index + turn log
 *   <root>/<yyyy>/<mm>/<dd>/<stamp>-<trigger>-<session>.md   snapshot (authoritative)
 *
 * Zero padded so lexicographic order === chronological order. Pure ASCII
 * names; Chinese only inside content.
 */

import { homedir } from 'node:os';
import { join } from 'node:path';

/**
 * The floor below which the tree refuses to create a node.
 *
 * This is a SANITY BOUND, not a statement about when the tree began: it exists
 * so a nonsense timestamp (an epoch of 0, a mangled field) cannot conjure a
 * 1970 directory that then lives in the tree forever. The tree's real earliest
 * day is simply whatever the earliest imported or recorded session produced.
 *
 * It was a hard-coded recent date once, which quietly made backfill impossible:
 * importing any history older than the constant was rejected, and the constant
 * described the machine it was written on rather than the tree it guarded.
 */
export const START_DATE = '2000-01-01';

/** Trigger kinds recorded in a snapshot file name and YAML header. */
export const TRIGGERS = Object.freeze(['pressure', 'compaction', 'manual', 'turns', 'import']);

/**
 * The default tree root, per platform.
 *
 * This used to be a hard-coded Windows drive literal on EVERY platform, which
 * is a trap rather than a default: a POSIX host that left `root` unset would
 * build `<letter>:\<name>\2026\09\14\2026-09-14.md`, which POSIX reads as ONE flat
 * file in the working directory whose name merely contains backslashes. It
 * succeeded, wrote real content, and left the configured tree empty. See
 * {@link assertRootForPlatform} — that failure mode is now a load-time error.
 */
export const DEFAULT_ROOT = join(homedir(), 'DSHMemory');

/** Window path component limit is 255; stay well below it. */
const MAX_COMPONENT = 120;

/** `session-deadbeef-0000-4000-8000-000000000000` and bare UUIDs both occur. */
const SESSION_INVALID = /[^A-Za-z0-9_-]/g;

/**
 * Pad a number to a fixed width with leading zeros.
 * @param {number} value - non-negative integer.
 * @param {number} [width] - target width.
 * @returns {string} zero-padded decimal text.
 */
export function pad(value, width = 2) {
	return String(value).padStart(width, '0');
}

/**
 * Reject a value that is not a non-negative safe integer.
 * @param {unknown} value - candidate.
 * @param {string} label - field name used in the error.
 * @returns {number} the validated number.
 */
function assertInt(value, label) {
	if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 0) {
		throw new TypeError(`memory-tree: ${label} must be a non-negative safe integer, got ${JSON.stringify(value)}`);
	}
	return value;
}

/**
 * Validate one digit-only path component (a year, month, or day field).
 *
 * Components are generated by this module, but they can also arrive from a
 * tool call argument, so they are validated rather than trusted: digits only
 * means no `..`, no separators, no drive letters, no Windows reserved names.
 * @param {unknown} value - candidate component.
 * @param {string} label - field name used in the error.
 * @returns {string} the validated component.
 */
export function assertDigitComponent(value, label) {
	const text = String(value);
	if (!/^[0-9]{1,4}$/.test(text)) {
		throw new TypeError(`memory-tree: ${label} must be 1-4 digits, got ${JSON.stringify(value)}`);
	}
	return text;
}

/**
 * Normalize a session id into a short, filesystem-safe token.
 * @param {unknown} sessionId - session id, with or without a `session-` prefix.
 * @returns {string} 8 characters of safe text, or `nosession` when absent.
 */
export function sessionToken(sessionId) {
	if (typeof sessionId !== 'string' || sessionId.length === 0) return 'nosession';
	const bare = sessionId.startsWith('session-') ? sessionId.slice('session-'.length) : sessionId;
	const safe = bare.replace(SESSION_INVALID, '');
	if (safe.length === 0) return 'nosession';
	return safe.slice(0, 8).toLowerCase();
}

/**
 * Format a date's local calendar fields in one IANA time zone.
 *
 * Uses `Intl` (full ICU is present in the Electron/Node runtime) and falls
 * back to a fixed +08:00 computation only if `Intl` rejects the request, so a
 * missing ICU database degrades instead of throwing.
 * @param {Date} date - the instant to project.
 * @param {string} timeZone - IANA zone name, e.g. `Asia/Shanghai`.
 * @returns {{year: number, month: number, day: number, hour: number, minute: number, second: number, stamp: string, dateText: string, offsetText: string}} local fields.
 */
export function localParts(date, timeZone = 'Asia/Shanghai') {
	if (!(date instanceof Date) || Number.isNaN(date.getTime())) {
		throw new TypeError('memory-tree: localParts requires a valid Date');
	}
	let fields;
	let offsetMinutes;
	try {
		const formatter = new Intl.DateTimeFormat('en-US', {
			timeZone,
			year: 'numeric',
			month: '2-digit',
			day: '2-digit',
			hour: '2-digit',
			minute: '2-digit',
			second: '2-digit',
			hour12: false,
			timeZoneName: 'longOffset'
		});
		const parts = new Map(formatter.formatToParts(date).map((part) => [part.type, part.value]));
		fields = {
			year: Number(parts.get('year')),
			month: Number(parts.get('month')),
			day: Number(parts.get('day')),
			// `hour12: false` still yields "24" for midnight in some ICU builds.
			hour: Number(parts.get('hour')) % 24,
			minute: Number(parts.get('minute')),
			second: Number(parts.get('second'))
		};
		offsetMinutes = parseOffset(parts.get('timeZoneName'));
	} catch {
		// Fallback: fixed +08:00, the established local zone for this tree.
		const shifted = new Date(date.getTime() + 8 * 3600 * 1000);
		fields = {
			year: shifted.getUTCFullYear(),
			month: shifted.getUTCMonth() + 1,
			day: shifted.getUTCDate(),
			hour: shifted.getUTCHours(),
			minute: shifted.getUTCMinutes(),
			second: shifted.getUTCSeconds()
		};
		offsetMinutes = 480;
	}
	for (const [key, value] of Object.entries(fields)) assertInt(value, `localParts.${key}`);
	return {
		...fields,
		stamp: `${fields.year}-${pad(fields.month)}-${pad(fields.day)} ${pad(fields.hour)}:${pad(fields.minute)}:${pad(fields.second)} ${offsetText(offsetMinutes)}`,
		dateText: `${fields.year}-${pad(fields.month)}-${pad(fields.day)}`,
		offsetText: offsetText(offsetMinutes)
	};
}

/**
 * Parse an ICU `longOffset` zone name such as `GMT+08:00`.
 * @param {string|undefined} text - the zone name part.
 * @returns {number} offset in minutes, defaulting to +08:00 when unparseable.
 */
function parseOffset(text) {
	if (typeof text !== 'string') return 480;
	const match = /GMT([+-])(\d{2}):?(\d{2})?/.exec(text);
	if (match === null) return text === 'GMT' || text === 'UTC' ? 0 : 480;
	const sign = match[1] === '-' ? -1 : 1;
	return sign * (Number(match[2]) * 60 + Number(match[3] ?? '0'));
}

/**
 * Render an offset in minutes as `+08:00`.
 * @param {number} minutes - offset in minutes.
 * @returns {string} the rendered offset.
 */
export function offsetText(minutes) {
	const sign = minutes < 0 ? '-' : '+';
	const abs = Math.abs(minutes);
	return `${sign}${pad(Math.floor(abs / 60))}:${pad(abs % 60)}`;
}

/**
 * Compare a local calendar date against the tree's start boundary.
 * @param {string} dateText - `yyyy-mm-dd`.
 * @returns {boolean} whether the date is recordable.
 */
export function isRecordableDate(dateText) {
	return typeof dateText === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(dateText) && dateText >= START_DATE;
}

/**
 * Split `yyyy-mm-dd` into validated components.
 * @param {string} dateText - the date to split.
 * @returns {{year: string, month: string, day: string}} zero-padded components.
 */
export function splitDate(dateText) {
	const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(dateText));
	if (match === null) throw new TypeError(`memory-tree: malformed date ${JSON.stringify(dateText)} (expected yyyy-mm-dd)`);
	const [, year, month, day] = match;
	const monthNumber = Number(month);
	const dayNumber = Number(day);
	// Validate the calendar BEFORE the range, so 2026-02-30 is reported as an
	// impossible date rather than as "before the tree start".
	if (monthNumber < 1 || monthNumber > 12) throw new RangeError(`memory-tree: ${dateText} has an invalid month`);
	const probe = new Date(Date.UTC(Number(year), monthNumber - 1, dayNumber));
	if (probe.getUTCMonth() !== monthNumber - 1 || probe.getUTCDate() !== dayNumber) {
		throw new RangeError(`memory-tree: ${dateText} is not a real calendar date`);
	}
	if (!isRecordableDate(dateText)) throw new RangeError(`memory-tree: ${dateText} is before the tree start ${START_DATE}`);
	return { year, month, day };
}

/**
 * The separator a root is written with.
 *
 * Decided from the ROOT, not from `process.platform`. Two reasons, and the
 * second is the one that matters:
 *
 *   1. The root is what the operator configured. A drive-letter path means Windows
 *      paths and `/srv/DSHMemory` means POSIX paths, whatever the host is.
 *   2. It makes these functions pure functions of their input, so a test can
 *      assert BOTH shapes on ANY platform. The original bug — a POSIX host
 *      quietly writing `<letter>:\<name>\2026\09\14\x.md` as one flat file — was
 *      invisible to a Windows-only test run. Now a test can pin the POSIX shape
 *      from Windows too.
 *
 * The FIRST separator wins, so a POSIX root whose name happens to contain a
 * backslash (which is exactly what that bug produced) is still read as POSIX.
 * @param {string} root - the configured tree root.
 * @returns {'\\'|'/'} the separator to join with.
 */
export function separatorOf(root) {
	const text = String(root);
	const backslash = text.indexOf('\\');
	const slash = text.indexOf('/');
	return backslash !== -1 && (slash === -1 || backslash < slash) ? '\\' : '/';
}

/**
 * Reject a root this platform cannot honour.
 *
 * A backslash-bearing root on POSIX is not a wrong-looking path, it is a
 * DIFFERENT path: `/` never follows the drive letter, so every joined path is a
 * single flat file in one directory. Writes succeed, content is correct, and
 * the configured tree stays empty — the failure has no symptom beyond absence.
 * That happened once (a Linux host configured with a Windows-shaped root), so it is a
 * throw rather than a warning.
 *
 * Windows needs no equivalent guard: it accepts both separators, so a POSIX
 * root still works there.
 * @param {unknown} root - the configured tree root.
 * @returns {string} the root, unchanged.
 * @throws when the root cannot address this platform's filesystem.
 */
export function assertRootForPlatform(root) {
	const text = String(root);
	if (process.platform !== 'win32' && text.includes('\\')) {
		throw new TypeError(
			`memory-tree: root ${JSON.stringify(text)} contains a backslash, but this platform (${process.platform}) ` +
				'treats "\\" as an ordinary file-name character, so every tree path would collapse into ONE flat file ' +
				'in the working directory while the configured root stayed empty. ' +
				'Point the root at a POSIX path, e.g. /srv/DSHMemory.'
		);
	}
	return text;
}

/**
 * Join path components with the separator the root itself is written with.
 * @param {string} root - absolute tree root, without a trailing separator.
 * @param {...string} parts - components to append.
 * @returns {string} the joined path.
 */
export function joinPath(root, ...parts) {
	const sep = separatorOf(root);
	const base = String(root).replace(/[\\/]+$/, '');
	const tail = parts.filter((part) => part !== undefined && part !== null && part !== '');
	if (tail.length === 0) return base;
	return `${base}${sep}${tail.join(sep)}`;
}

/**
 * Every path a tree node owns. Derived from one root plus one local date.
 *
 * Created lazily by the writer — this function only computes names, so it is
 * safe to call for a date whose directories do not exist yet.
 * @param {string} root - absolute tree root.
 * @param {string} dateText - `yyyy-mm-dd` local date.
 * @returns {{root: string, index: string, longterm: string, yearDir: string, yearFile: string, monthDir: string, monthFile: string, dayDir: string, dayFile: string, date: {year: string, month: string, day: string}, dateText: string}} the node layout.
 */
export function nodePaths(root, dateText) {
	if (typeof root !== 'string' || root.length === 0) throw new TypeError('memory-tree: root must be a non-empty string');
	const { year, month, day } = splitDate(dateText);
	const yearDir = joinPath(root, year);
	const monthDir = joinPath(yearDir, month);
	const dayDir = joinPath(monthDir, day);
	return {
		root: root.replace(/[\\/]+$/, ''),
		index: joinPath(root, 'index.md'),
		longterm: joinPath(root, 'longterm.md'),
		yearDir,
		yearFile: joinPath(yearDir, `${year}.md`),
		monthDir,
		monthFile: joinPath(monthDir, `${year}-${month}.md`),
		dayDir,
		dayFile: joinPath(dayDir, `${year}-${month}-${day}.md`),
		date: { year, month, day },
		dateText
	};
}

/**
 * Resolve a drill-down level plus an optional date to the file that holds it.
 * @param {string} root - absolute tree root.
 * @param {'index'|'longterm'|'year'|'month'|'day'} level - tree level.
 * @param {string} [dateText] - required for every level except `index` and `longterm`.
 * @returns {{path: string, level: string, dateText: string|undefined}} the resolved node.
 */
export function levelPath(root, level, dateText) {
	switch (level) {
		case 'index':
			return { path: joinPath(root, 'index.md'), level, dateText: undefined };
		case 'longterm':
			return { path: joinPath(root, 'longterm.md'), level, dateText: undefined };
		case 'year':
		case 'month':
		case 'day': {
			if (typeof dateText !== 'string') throw new TypeError(`memory-tree: level "${level}" requires a date (yyyy-mm-dd)`);
			const paths = nodePaths(root, dateText);
			return { path: level === 'year' ? paths.yearFile : level === 'month' ? paths.monthFile : paths.dayFile, level, dateText };
		}
		default:
			throw new TypeError(`memory-tree: unknown level ${JSON.stringify(level)}`);
	}
}

/**
 * Build a snapshot file name: `<yyyy>-<mm>-<dd>T<HHMMSS>-<trigger>-<session>.md`.
 *
 * Unique by construction (second resolution + session token), which is what
 * lets two concurrent sessions snapshot the same day without colliding.
 * @param {string} dateText - `yyyy-mm-dd` local date.
 * @param {{hour: number, minute: number, second: number}} time - local time fields.
 * @param {string} trigger - one of {@link TRIGGERS}.
 * @param {unknown} sessionId - owning session.
 * @returns {string} the file name (no directory).
 */
export function snapshotName(dateText, time, trigger, sessionId) {
	splitDate(dateText);
	if (!TRIGGERS.includes(trigger)) throw new TypeError(`memory-tree: unknown trigger ${JSON.stringify(trigger)}`);
	const { year, month, day } = splitDate(dateText);
	const clock = `${pad(assertInt(time?.hour, 'time.hour'))}${pad(assertInt(time?.minute, 'time.minute'))}${pad(assertInt(time?.second, 'time.second'))}`;
	const name = `${year}-${month}-${day}T${clock}-${trigger}-${sessionToken(sessionId)}.md`;
	if (name.length > MAX_COMPONENT) throw new RangeError(`memory-tree: snapshot name too long (${name.length})`);
	return name;
}

/**
 * Test whether a path is inside the tree root (defence in depth for any path
 * that was assembled from external input).
 *
 * Comparison follows the ROOT's shape, not the platform's. A Windows-shaped
 * root is compared case-insensitively with either separator folded; a POSIX root
 * is compared case-sensitively and a backslash stays an ordinary character.
 * Both halves matter: folding case on POSIX would widen the fence (`/srv/dshmemory`
 * would count as inside `/srv/DSHMemory`), and folding `\` would invent a path
 * boundary the filesystem does not have.
 * @param {string} root - absolute tree root.
 * @param {string} candidate - path to test.
 * @returns {boolean} whether `candidate` is the root or sits below it.
 */
export function isInsideRoot(root, candidate) {
	const sep = separatorOf(root);
	const windows = sep === '\\';
	const normalize = (value) => {
		const text = String(value).replace(/[\\/]+$/, '');
		return windows ? text.replace(/\//g, '\\').toLowerCase() : text;
	};
	const base = normalize(root);
	const target = normalize(candidate);
	return target === base || target.startsWith(`${base}${sep}`);
}
